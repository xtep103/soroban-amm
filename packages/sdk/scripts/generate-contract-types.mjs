#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = resolve(here, "..");
const repoRoot = resolve(sdkRoot, "..", "..");
const output = resolve(sdkRoot, "src/generated/contract-metadata.ts");
const contracts = {
  staking: "contracts/staking/src/lib.rs",
  incentive_campaigns: "contracts/incentive_campaigns/src/lib.rs",
  pol_vesting: "contracts/pol_vesting/src/lib.rs",
  oracle_aggregator: "contracts/oracle_aggregator/src/lib.rs",
  twap_consumer: "contracts/twap_consumer/src/lib.rs",
  twal_consumer: "contracts/twal_consumer/src/lib.rs",
  dex_aggregator: "contracts/dex_aggregator/src/lib.rs",
  batch_auction: "contracts/batch_auction/src/lib.rs",
};

function parse(source) {
  const errors = {};
  const errorBlock = source.match(/#\[contracterror\][\s\S]*?pub enum\s+\w+\s*\{([\s\S]*?)\n\}/);
  if (errorBlock) {
    for (const match of errorBlock[1].matchAll(/^\s*(\w+)\s*=\s*(\d+),/gm)) {
      errors[Number(match[2])] = match[1];
    }
  }
  const structs = {};
  for (const match of source.matchAll(/#\[contracttype\][\s\S]{0,160}?pub struct\s+(\w+)\s*\{([\s\S]*?)\n\}/g)) {
    structs[match[1]] = [...match[2].matchAll(/^\s*pub\s+(\w+)\s*:\s*([^,]+),/gm)]
      .map((field) => ({ name: field[1], type: field[2].trim() }));
  }
  return { errors, structs };
}

const metadata = {};
for (const [name, path] of Object.entries(contracts)) {
  metadata[name] = parse(readFileSync(resolve(repoRoot, path), "utf8"));
}
const serialized = `// Generated by scripts/generate-contract-types.mjs. Do not edit.\n` +
  `export const CONTRACT_METADATA = ${JSON.stringify(metadata, null, 2)} as const;\n` +
  `export type ContractKind = keyof typeof CONTRACT_METADATA;\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(output, "utf8"); } catch {}
  if (current !== serialized) {
    console.error("Generated contract metadata is stale. Run npm run generate:abi.");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, serialized);
}
